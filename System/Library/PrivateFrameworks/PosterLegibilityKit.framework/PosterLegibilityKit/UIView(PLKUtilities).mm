@interface UIView(PLKUtilities)
- (void)plk_setBoundsAndPositionFromFrame:()PLKUtilities;
@end

@implementation UIView(PLKUtilities)

- (void)plk_setBoundsAndPositionFromFrame:()PLKUtilities
{
  [self bounds];
  [self setBounds:?];
  layer = [self layer];
  [layer anchorPoint];

  return [self setCenter:?];
}

@end